def shade(cell, hex_color):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), hex_color)
    shd.set(qn("w:val"), "clear")
    tcPr.append(shd)


def font(run, size=11, bold=False, color=DARK, name="Calibri"):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)
    rFonts.set(qn("w:cs"), name)
    rFonts.set(qn("w:eastAsia"), name)


def pset(p, after=6, before=0, align=None):
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    if align:
        p.alignment = align


def add_title(doc, text):
    p = doc.add_paragraph()
    pset(p, after=4, align=WD_ALIGN_PARAGRAPH.LEFT)
    r = p.add_run(text)
    font(r, 22, True, NAVY)


def add_h(doc, text):
    p = doc.add_paragraph()
    pset(p, after=8, before=14)
    r = p.add_run(text)
    font(r, 16, True, NAVY)


def add_h2(doc, text):
    p = doc.add_paragraph()
    pset(p, after=6, before=10)
    r = p.add_run(text)
    font(r, 13, True, NAVY)


def add_body(doc, text):
    p = doc.add_paragraph()
    pset(p, after=8)
    r = p.add_run(text)
    font(r, 11, False, DARK)
    return p


def add_note(doc, text):
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.cell(0, 0)
    shade(cell, NOTE_BG)
    p = cell.paragraphs[0]
    pset(p, after=0)
    r = p.add_run(text)
    font(r, 11, False, DARK)
    doc.add_paragraph()


def add_bullet(doc, text):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.space_before = Pt(0)
    p.clear()
    r = p.add_run(text)
    font(r, 11, False, DARK)


def table(doc, headers, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        shade(cell, HEADER_BG)
        p = cell.paragraphs[0]
        pset(p, after=0)
        r = p.add_run(h)
        font(r, 10, True, WHITE)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = t.rows[ri + 1].cells[ci]
            if ri % 2 == 1:
                shade(cell, ALT_BG)
            p = cell.paragraphs[0]
            pset(p, after=0)
            r = p.add_run(str(val))
            font(r, 10, False, DARK)
    doc.add_paragraph()
    return t


